#!/usr/bin/env python3
"""Copy the deployable site into OUTPUT_DIR, skipping everything matched by deploy/exclude.txt.

Pattern forms (one per line, '#' starts a comment):
  /dir/   root-anchored directory prefix
  /file   root-anchored path, glob allowed
  name    basename glob matched at any depth
"""
import fnmatch
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MARKER = ".site-build"


def load_patterns():
    text = (ROOT / "deploy" / "exclude.txt").read_text(encoding="utf-8")
    return [line.strip() for line in text.splitlines() if line.strip() and not line.strip().startswith("#")]


def is_excluded(rel: pathlib.PurePosixPath, patterns) -> bool:
    rel_str = rel.as_posix()
    for pattern in patterns:
        if pattern.startswith("/") and pattern.endswith("/"):
            if rel_str.startswith(pattern[1:]):
                return True
        elif pattern.startswith("/"):
            if fnmatch.fnmatchcase(rel_str, pattern[1:]):
                return True
        elif fnmatch.fnmatchcase(rel.name, pattern):
            return True
    return False


def prepare_output(out: pathlib.Path):
    if out.exists():
        # Only ever delete a directory this script created, never an arbitrary path.
        if not (out / MARKER).is_file():
            sys.exit(f"refusing to overwrite {out}: not a previous build (missing {MARKER})")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by deploy/build_site.py\n", encoding="utf-8")


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: build_site.py OUTPUT_DIR")
    out = pathlib.Path(sys.argv[1]).resolve()
    patterns = load_patterns()
    prepare_output(out)
    count = size = 0
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or out in path.parents:
            continue
        rel = pathlib.PurePosixPath(path.relative_to(ROOT).as_posix())
        if is_excluded(rel, patterns):
            continue
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        count += 1
        size += path.stat().st_size
    print(f"built {count} files ({size / 1_048_576:.1f} MiB) into {out}")


if __name__ == "__main__":
    main()
